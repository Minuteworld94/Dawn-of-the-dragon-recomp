// Copies big-endian 32-bit words, swapping each (bytes: a multiple of 4). 64 bytes per step with
// SSSE3 byte shuffles and 16-byte stores - the destination is usually the upload ring (write-
// combined GPU memory, slow with 4-byte stores). Vertices were ~6.5 ms a frame in Avalar with the
// word-by-word loop (WORK_LOG 124).
__attribute__((target("ssse3"))) void CopySwapped32(uint8_t* dst, const uint8_t* src, uint32_t bytes) {
  const __m128i swap = _mm_setr_epi8(3, 2, 1, 0, 7, 6, 5, 4, 11, 10, 9, 8, 15, 14, 13, 12);
  uint32_t i = 0;
  for (; i + 64 <= bytes; i += 64) {
    __m128i a = _mm_loadu_si128(reinterpret_cast<const __m128i*>(src + i));
    __m128i b = _mm_loadu_si128(reinterpret_cast<const __m128i*>(src + i + 16));
    __m128i c = _mm_loadu_si128(reinterpret_cast<const __m128i*>(src + i + 32));
    __m128i d = _mm_loadu_si128(reinterpret_cast<const __m128i*>(src + i + 48));
    _mm_storeu_si128(reinterpret_cast<__m128i*>(dst + i), _mm_shuffle_epi8(a, swap));
    _mm_storeu_si128(reinterpret_cast<__m128i*>(dst + i + 16), _mm_shuffle_epi8(b, swap));
    _mm_storeu_si128(reinterpret_cast<__m128i*>(dst + i + 32), _mm_shuffle_epi8(c, swap));
    _mm_storeu_si128(reinterpret_cast<__m128i*>(dst + i + 48), _mm_shuffle_epi8(d, swap));
  }
  for (; i + 16 <= bytes; i += 16)
    _mm_storeu_si128(reinterpret_cast<__m128i*>(dst + i),
                     _mm_shuffle_epi8(_mm_loadu_si128(reinterpret_cast<const __m128i*>(src + i)), swap));
  for (; i + 4 <= bytes; i += 4) {
    uint32_t v;
    std::memcpy(&v, src + i, 4);
    v = __builtin_bswap32(v);
    std::memcpy(dst + i, &v, 4);
  }
}

uint64_t Fnv(const void* data, size_t size, uint64_t h = 1469598103934665603ull) {
  auto p = static_cast<const uint8_t*>(data);
  for (size_t i = 0; i < size; ++i) h = (h ^ p[i]) * 1099511628211ull;
  return h;
}

// ---- shader cache (spyro_shaders.bin, written by SpyroShaderRecomp) ----------------------------
struct CacheEntry {
  uint64_t hash;
  uint32_t dxil_offset, dxil_size, spirv_offset, spirv_size, flags, spec_mask;
};
std::vector<uint8_t> g_cache_file;
std::unordered_map<uint64_t, CacheEntry> g_cache;

void LoadShaderCache() {
  if (std::getenv("SPYRO_NOSHADERCACHE")) {  // test: every shader goes through runtime translation
    REXLOG_INFO("[plume] SPYRO_NOSHADERCACHE: spyro_shaders.bin not loaded");
    return;
  }
  std::ifstream f("spyro_shaders.bin", std::ios::binary);
  if (!f) {
    REXLOG_INFO("[plume] spyro_shaders.bin not found - every shader is translated at runtime (shader_cache\\)");
    return;
  }
  g_cache_file.assign(std::istreambuf_iterator<char>(f), std::istreambuf_iterator<char>());
  uint32_t magic = 0, count = 0;
  std::memcpy(&magic, g_cache_file.data(), 4);
  std::memcpy(&count, g_cache_file.data() + 8, 4);
  if (magic != 0x43535053) {
    REXLOG_ERROR("[plume] spyro_shaders.bin has a bad header");
    return;
  }
  for (uint32_t i = 0; i < count; ++i) {
    CacheEntry e;
    std::memcpy(&e, g_cache_file.data() + 16 + 32 * i, 32);
    g_cache[e.hash] = e;
  }
  REXLOG_INFO("[plume] shader cache: {} shaders ({} KB)", g_cache.size(), g_cache_file.size() / 1024);
}

