struct HostTarget {
  std::unique_ptr<RenderTexture> texture;
  RenderFormat format = RenderFormat::UNKNOWN;
  uint32_t width = 0, height = 0;              // host texture size
  uint32_t guest_width = 0, guest_height = 0;  // the surface as the game created it
  float scale = 1.0f;                          // Resolution setting it was made for
  bool tiled = false;  // a band surface of predicated tiling (SetPredication used while bound)
  RenderTextureLayout layout = RenderTextureLayout::UNKNOWN;
  bool depth = false;
  std::unique_ptr<RenderTextureView> depth_view;  // depth read as a texture (depth Resolve)
  uint32_t depth_descriptor = 0;
};

// A texture the game filled with Resolve (EDRAM -> texture copy): lives on the GPU, found by the
