// ---- shaders ------------------------------------------------------------------------------------
RenderShader* ShaderFor(GuestShader& s) {
  if (s.shader) return s.shader.get();
  if (s.missing) return nullptr;
  auto it = g_cache.find(s.hash);
  if (it == g_cache.end()) {
    // Translated at runtime (WORK_LOG 121): its draws are skipped until it is ready.
    std::vector<uint8_t> dxil;
    switch (shader_translator::Get(s.hash, &dxil)) {
      case shader_translator::State::kPending:
        return nullptr;
      case shader_translator::State::kReady:
        s.shader = g.device->createShader(dxil.data(), dxil.size(), "main", RenderShaderFormat::DXIL);
        if (!s.shader) s.missing = true;
        return s.shader.get();
      case shader_translator::State::kFailed:
        s.missing = true;
        REXLOG_INFO("[plume] shader {:016X} ({}) not in spyro_shaders.bin and not translatable", s.hash,
                    s.pixel ? "pixel" : "vertex");
        return nullptr;
    }
  }
  const CacheEntry& e = it->second;
  // Debug: shader_override\<HASH>.dxil (in the run folder) replaces a shader with a hand-edited
  // build (analysis\hlsl\<HASH>.hlsl compiled with TOOLS dxc) - WORK_LOG 112.
  char override_path[64];
  std::snprintf(override_path, sizeof(override_path), "shader_override/%016llX.dxil",
                static_cast<unsigned long long>(s.hash));
  if (std::ifstream o{override_path, std::ios::binary}) {
    std::vector<char> dxil((std::istreambuf_iterator<char>(o)), std::istreambuf_iterator<char>());
    s.shader = g.device->createShader(dxil.data(), dxil.size(), "main", RenderShaderFormat::DXIL);
    REXLOG_INFO("[plume] shader {:016X} replaced by {}", s.hash, override_path);
    if (!s.shader) s.missing = true;
    return s.shader.get();
  }
  s.shader = g.device->createShader(g_cache_file.data() + e.dxil_offset, e.dxil_size, "main", RenderShaderFormat::DXIL);
  if (!s.shader) s.missing = true;
  return s.shader.get();
}

