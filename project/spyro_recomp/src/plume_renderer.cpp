bool LoggingFrame() {
  static const uint32_t s_log_frame = [] {
    const char* v = std::getenv("SPYRO_PLUMEDRAWS");
    return v ? uint32_t(std::atoi(v)) : 0u;
  }();
  // Env SPYRO_PLUMEDRAWS_AT=<s>[,<s>...]: the first frame after each of those seconds since the
  // renderer started (frame numbers drift between runs; WORK_LOG 111).
  static std::vector<double> s_times = [] {
    std::vector<double> t;
    if (const char* v = std::getenv("SPYRO_PLUMEDRAWS_AT"))
      for (const char* p = v; *p;) {
        t.push_back(std::atof(p));
        while (*p && *p != ',') ++p;
        if (*p) ++p;
      }
    return t;
  }();
  static const auto s_start = std::chrono::steady_clock::now();
  static uint32_t s_frame_logging = UINT32_MAX;
  if (!s_times.empty() && s_frame_logging != g.frame && Seconds(s_start) >= s_times.front()) {
    s_times.erase(s_times.begin());
    s_frame_logging = g.frame + 1;  // the whole next frame (this one is already under way)
  }
  return (s_log_frame && g.frame == s_log_frame) || s_frame_logging == g.frame || g_key_log_frame == g.frame;
}

