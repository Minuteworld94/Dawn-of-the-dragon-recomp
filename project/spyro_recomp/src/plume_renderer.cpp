// X360 vertex declaration type -> host format (data already byte-swapped per 32-bit word).
RenderFormat VertexFormat(uint32_t type, bool as_uint) {
  switch (type) {
    case 0x002A23B9: return as_uint ? RenderFormat::R32G32B32_UINT : RenderFormat::R32G32B32_FLOAT;  // FLOAT3
    case 0x002C23A5: return as_uint ? RenderFormat::R32G32_UINT : RenderFormat::R32G32_FLOAT;        // FLOAT2
    case 0x001A23A6: return as_uint ? RenderFormat::R32G32B32A32_UINT : RenderFormat::R32G32B32A32_FLOAT;  // FLOAT4
    case 0x002C83A4: return as_uint ? RenderFormat::R32_UINT : RenderFormat::R32_FLOAT;               // FLOAT1
    case 0x00182886: return as_uint ? RenderFormat::R8G8B8A8_UINT : RenderFormat::B8G8R8A8_UNORM;    // D3DCOLOR
    case 0x001A2286: return as_uint ? RenderFormat::R8G8B8A8_UINT : RenderFormat::R8G8B8A8_UINT;     // UBYTE4
    case 0x001A2086: return as_uint ? RenderFormat::R8G8B8A8_UINT : RenderFormat::R8G8B8A8_UNORM;    // UBYTE4N
    default: return RenderFormat::UNKNOWN;
  }
}

// Packed X360 vertex types decoded on the CPU to 4 floats (WORK_LOG 106): D3D12 has no signed
// 10:10:10:2 or 16-bit "scaled" formats, and the translated shaders read NORMAL / TANGENT /
// BINORMAL as raw float bits (tfetchR11G11B10 -> asfloat). `w` = the element's dwords after
// the 32-bit swap; Xenos takes component X from the low bits.
float HalfToFloat(uint16_t h) {
  uint32_t sign = uint32_t(h >> 15) << 31, exp = (h >> 10) & 0x1F, man = h & 0x3FF, bits;
  if (exp == 0) {
    float f = std::ldexp(float(man), -24);
    return sign ? -f : f;
  }
  bits = exp == 31 ? (sign | 0x7F800000u | (man << 13)) : (sign | ((exp + 112) << 23) | (man << 13));
  float f;
  std::memcpy(&f, &bits, 4);
  return f;
}

bool DecodePacked(uint32_t type, const uint32_t* w, float* out) {
  auto s = [](uint32_t v, int bits) { return int32_t(v << (32 - bits)) >> (32 - bits); };
  out[0] = out[1] = out[2] = 0.0f;
  out[3] = 1.0f;
  switch (type) {
    case 0x002A2187: case 0x001A2187:  // DEC3N / DEC4N
      for (int i = 0; i < 3; ++i) out[i] = std::max(float(s(w[0] >> (10 * i), 10)) / 511.0f, -1.0f);
      if (type == 0x001A2187) out[3] = std::max(float(s(w[0] >> 30, 2)), -1.0f);
      return true;
    case 0x002A2087: case 0x001A2087:  // UDEC3N / UDEC4N
      for (int i = 0; i < 3; ++i) out[i] = float((w[0] >> (10 * i)) & 0x3FF) / 1023.0f;
      if (type == 0x001A2087) out[3] = float(w[0] >> 30) / 3.0f;
      return true;
    case 0x002A2387: case 0x002A2287:  // DEC3 / UDEC3
      for (int i = 0; i < 3; ++i)
        out[i] = type == 0x002A2387 ? float(s(w[0] >> (10 * i), 10)) : float((w[0] >> (10 * i)) & 0x3FF);
      return true;
    case 0x002C2159: case 0x001A215A:  // SHORT2N / SHORT4N
    case 0x002C2359: case 0x001A235A:  // SHORT2 / SHORT4
    case 0x002C2059: case 0x001A205A:  // USHORT2N / USHORT4N
    case 0x002C2259: case 0x001A225A:  // USHORT2 / USHORT4
    case 0x002C235F: case 0x001A2360: {  // FLOAT16_2 / FLOAT16_4
      // After the 32-bit swap the first 16-bit value of each dword is in the HIGH half
      // (UnleashedRecomp swaps these texcoords too: video.cpp swappedTexcoords).
      int n = (type >> 20) == 0x2 ? 2 : 4;
      for (int i = 0; i < n; ++i) {
        uint32_t v = (w[i / 2] >> (16 * (1 - (i & 1)))) & 0xFFFF;
        switch (type & 0xFFF) {
          case 0x159: case 0x15A: out[i] = std::max(float(int16_t(v)) / 32767.0f, -1.0f); break;
          case 0x359: case 0x35A: out[i] = float(int16_t(v)); break;
          case 0x059: case 0x05A: out[i] = float(v) / 65535.0f; break;
          case 0x259: case 0x25A: out[i] = float(v); break;
          default: out[i] = HalfToFloat(uint16_t(v)); break;
        }
      }
      return true;
    }
    case 0x001A2086: case 0x001A2186:  // UBYTE4N / BYTE4N
    case 0x001A2286: case 0x001A2386:  // UBYTE4 / BYTE4
      for (int i = 0; i < 4; ++i) {
        uint32_t v = (w[0] >> (8 * i)) & 0xFF;
        out[i] = type == 0x001A2086 ? float(v) / 255.0f
               : type == 0x001A2186 ? std::max(float(int8_t(v)) / 127.0f, -1.0f)
               : type == 0x001A2286 ? float(v) : float(int8_t(v));
      }
      return true;
    case 0x00182886:  // D3DCOLOR (B8G8R8A8)
      out[0] = float((w[0] >> 16) & 0xFF) / 255.0f;
      out[1] = float((w[0] >> 8) & 0xFF) / 255.0f;
      out[2] = float(w[0] & 0xFF) / 255.0f;
      out[3] = float(w[0] >> 24) / 255.0f;
      return true;
    default:
      return false;
  }
}

uint32_t PackedDwords(uint32_t type) { return (type & 0xFFF) == 0x15A || (type & 0xFFF) == 0x35A || (type & 0xFFF) == 0x05A || (type & 0xFFF) == 0x25A || type == 0x001A2360 ? 2 : 1; }

struct DeclElement {
  uint32_t offset, type, usage, index, stream;
};

constexpr uint32_t kZeroSlot = 15;  // input slot of the zero inputs a shader reads but no stream has

bool ReadDecl(const uint8_t* base, uint32_t decl, std::vector<DeclElement>& out) {
  if (!decl || !GuestReadable(base, decl, 0x34)) return false;
  uint32_t count = Load32(base, decl + 0x18);
  if (count > 16 || !GuestReadable(base, decl + 0x34, 12 * count)) return false;
  for (uint32_t i = 0; i < count; ++i) {
    uint32_t w0 = Load32(base, decl + 0x34 + 12 * i), type = Load32(base, decl + 0x38 + 12 * i),
             w2 = Load32(base, decl + 0x3C + 12 * i);
    if ((w0 >> 16) == 0xFF) break;
    if ((w0 >> 16) >= kZeroSlot) continue;
    out.push_back({w0 & 0xFFFF, type, (w2 >> 16) & 0xFF, (w2 >> 8) & 0xFF, w0 >> 16});
  }
  return !out.empty();
}

