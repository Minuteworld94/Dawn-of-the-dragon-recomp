// The alpha channel's factor. Xenos (like D3D9) accepts colour factors there and uses their
// alpha (SRC_COLOR's alpha is source alpha); D3D12 rejects them: pipeline creation failed and
// the next draw crashed inside D3D12 when the second level loaded (WORK_LOG 118).
RenderBlend AlphaBlendFactor(uint32_t f) {
  switch (RenderBlend b = BlendFactor(f)) {
    case RenderBlend::SRC_COLOR: return RenderBlend::SRC_ALPHA;
    case RenderBlend::INV_SRC_COLOR: return RenderBlend::INV_SRC_ALPHA;
    case RenderBlend::DEST_COLOR: return RenderBlend::DEST_ALPHA;
    case RenderBlend::INV_DEST_COLOR: return RenderBlend::INV_DEST_ALPHA;
    default: return b;
  }
}

