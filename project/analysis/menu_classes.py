"""List every CKS08Menu* class: its vtable address and selected vtable slots.

Usage: py -3 -I menu_classes.py <image_dump.bin> [--gen <out.inc>]

Record layout in .rdata (WORK_LOG 49): [display name][class name][vtable...]. The vtable begins
right after the class name's NUL, aligned to 4. Verified for Video (0x8207A360, which its
constructor stores) and Sound (0x8207A238, slot 57 = 0x822E0948, the handler seen at runtime).

--gen writes a C++ include for spyro_hooks.cpp: a vtable->class-name table plus one wrapper per
slot-57 function that belongs to exactly one menu class (shared base stubs are left alone so
non-menu objects don't flood the log).
"""
import re
import struct
import sys

IMG_BASE = 0x82000000
img = open(sys.argv[1], "rb").read()
gen_path = sys.argv[sys.argv.index("--gen") + 1] if "--gen" in sys.argv else None

CODE_LO, CODE_HI = 0x820B0000, 0x826DF1BC
SLOT = 57


def word(addr):
    o = addr - IMG_BASE
    return struct.unpack(">I", img[o:o + 4])[0]


classes = []
for m in re.finditer(rb"CKS08Menu[A-Za-z0-9_]+\x00", img):
    name_addr = IMG_BASE + m.start()
    name = m.group()[:-1].decode()
    vt = (name_addr + len(name) + 1 + 3) & ~3
    slot57 = word(vt + SLOT * 4)
    first = word(vt)
    ok = CODE_LO <= first < CODE_HI and CODE_LO <= slot57 < CODE_HI
    classes.append((name, vt, slot57, ok))

owners = {}
for name, vt, s, ok in classes:
    if ok:
        owners.setdefault(s, []).append(name)

print(f"{'class':28s} {'vtable':10s} slot57      shared")
for name, vt, s, ok in classes:
    flag = "" if ok else "  (NOT A VTABLE?)"
    shared = len(owners.get(s, [])) if ok else 0
    print(f"{name:28s} 0x{vt:08X} 0x{s:08X}  {shared}{flag}")

if gen_path:
    unique = sorted(s for s, names in owners.items() if len(names) == 1)
    with open(gen_path, "w") as f:
        f.write("// AUTO-GENERATED by project/analysis/menu_classes.py - do not hand edit.\n")
        f.write("// Included by spyro_hooks.cpp.\n\n")
        f.write("static const MenuClassInfo kMenuClasses[] = {\n")
        for name, vt, s, ok in classes:
            if ok:
                f.write(f'    {{0x{vt:08X}u, "{name}"}},\n')
        f.write("};\n\n")
        for s in unique:
            f.write(f"MENU_SLOT57_HOOK(sub_{s:08X})\n")
    print(f"\nwrote {gen_path}: {len(classes)} classes, {len(unique)} unique slot-57 hooks")
